$ErrorActionPreference = 'Stop'
$ProjectDir = "C:\Users\User\moss-and-daisy"
$ImagesRoot = Join-Path $ProjectDir "public\images"
$OutFile = Join-Path $ProjectDir "src\data\customImageMap.ts"
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$Entries = New-Object System.Collections.Generic.List[string]
$Dirs = Get-ChildItem -Path $ImagesRoot -Directory -Recurse
foreach ($d in $Dirs) {
  $imgs = Get-ChildItem -Path $d.FullName -File | Where-Object { $_.Extension -match '^\.(png|jpg|jpeg|webp)$' } | Sort-Object LastWriteTime -Descending
  if ($imgs.Count -gt 0) {
    $relFolder = $d.FullName.Substring($ImagesRoot.Length + 1).Replace("\", "/")
    $relFile = "/images/" + $relFolder + "/" + $imgs[0].Name
    $Entries.Add("  `"$relFolder`": `"$relFile`",")
  }
}
$Ts = @(
  "// Auto-generated by sync-images.ps1",
  "export const CUSTOM_IMAGE_MAP: Record<string, string> = {",
  ($Entries -join "`r`n"),
  "};",
  "export function resolveAssetImage(folderPath: string): string {",
  "  return CUSTOM_IMAGE_MAP[folderPath] ?? `"/images/`" + folderPath + `"/preview.svg`";",
  "}"
) -join "`r`n"
[System.IO.File]::WriteAllText($OutFile, $Ts, $Utf8NoBom)
Write-Host ("Synced " + $Entries.Count + " realistic folder images into src/data/customImageMap.ts") -ForegroundColor Green