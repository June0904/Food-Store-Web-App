$ErrorActionPreference = 'Stop'
$ProjectDir = "C:\Users\User\moss-and-daisy"
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$PublicImages = Join-Path $ProjectDir "public\images"
$Entries = @()

Get-ChildItem -Path $PublicImages -Directory -Recurse | ForEach-Object {
    $Dir = $_
    $CustomFile = Get-ChildItem -Path $Dir.FullName -File | Where-Object {
        $_.Extension -match '^\.(png|jpg|jpeg|webp|avif|gif)$' -or ($_.Extension -eq '.svg' -and $_.Name -ne 'preview.svg')
    } | Select-Object -First 1

    if ($CustomFile) {
        $RelDir = $Dir.FullName.Substring((Join-Path $ProjectDir "public").Length).Replace('\', '/')
        $RelFile = $RelDir + "/" + $CustomFile.Name
        $Entries += "  '" + $RelDir + "': '" + $RelFile + "',"
    }
}

$Lines = @(
    "// Auto-generated by sync-images.ps1",
    "export const CUSTOM_IMAGE_MAP: Record<string, string> = {",
    ($Entries -join "`r`n"),
    "};",
    "",
    "export function resolveAssetImage(folderPath: string): string {",
    "  const clean = folderPath.replace(/\/preview\.svg$/, '').replace(/\/$/, '');",
    "  return CUSTOM_IMAGE_MAP[clean] ?? (clean + '/preview.svg');",
    "}"
)

$DataDir = Join-Path $ProjectDir "src\data"
if (-not (Test-Path $DataDir)) { New-Item -ItemType Directory -Path $DataDir -Force | Out-Null }
[System.IO.File]::WriteAllText((Join-Path $DataDir "customImageMap.ts"), ($Lines -join "`r`n"), $Utf8NoBom)
Write-Host "Synced custom images ($($Entries.Count) custom files found)." -ForegroundColor Green